console.log(hasilKurung); // Hasil Kurung = 90





// ===== COMPARISON =====

// Operator Sama Dengan (==)
var pw = "iqis_12345";
var pw2 = "iqis_12345";
var hasil = pw == pw2;
console.log(hasil); // hasil = true

// Operator Tidak Sama Dengan (!=)
var pw3 = "izin_doeloe";
var pw4 = "izin_dulu";
var hasil2 = pw3 != pw4;
console.log(hasil2); // hasil = true

// Operator Lebih Besar (>)
let umur = 25;
let umur2 = 20;
let lebihBesar = umur > umur2;
console.log(lebihBesar); // Lebih Besar = true

// Operator Lebih Kecil (<)
var tinggi = 170;
var tinggi2 = 180;
var lebihKecil = tinggi < tinggi2;
console.log(lebihKecil); // Lebih Kecil = false

// Operator Lebih Besar atau Sama Dengan (>=)
var nilai = 80;
let nilai2 = 75;
let output = nilai >= nilai2;
console.log(output); // Lebih Besar atau Sama Dengan = true

// Operator Lebih Kecil atau Sama Dengan (<=)
var nilai3 = 70;
var nilai4 = 75;
var output2 = nilai3 <= nilai4;
console.log(output2); // Lebih Kecil atau Sama Dengan = true

// Operator Identik (===)
var angka = 10;
var angka2 = "10";
var identik = angka === angka2;
console.log(identik); // Identik = false

// Operator Tidak Identik (!==)
var number1 = 10;
var number2 = "10";
var isN1NotEqualN2 = number1 !== number2;
console.log(isN1NotEqualN2); // Tidak Identik = true





// ===== LOGICAL =====
var x = 10;
var y = 20;
// Operator AND (&&)
var hasilAnd = (x > 5) && (y < 25);
console.log(hasilAnd); // Hasil AND = true

// Operator OR (||)
var hasilOr = (x < 5) || (y < 25);
console.log(hasilOr); // Hasil OR = true

// Operator NOT (!)
var hasilNot = !(x > 5);
console.log(hasilNot); // Hasil NOT = false





