// ===== ARITHMETIC =====

// Operator Jumlah (+)
var a = 30;
var b = 15;
var jumlah = a + b;

console.log(jumlah); // Jumlah = 45

// Operator Pengurangan (-)
var c = 30;
var d = 15;
var selisih = c - d;

console.log(selisih); // Selisih = 15

// Operator Perkalian (*)
var e = 30;
var f = 15;
var hasilKali = e * f;

console.log(hasilKali); // Hasil Kali = 450

// Operator Pembagian (/)
var g = 30;
var h = 15;
var hasilBagi = g / h;

console.log(hasilBagi); // Hasil Bagi = 2

// Operator Sisa Bagi (%)
var i = 30;
var j = 15;
var sisaBagi = i % j;

console.log(sisaBagi); // Sisa Bagi = 0

// Operator Kurung ()
var k = 30;
var l = 15;
